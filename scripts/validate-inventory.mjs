import fs from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";
const source = fs.readFileSync(new URL("../app/farm-state.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { PACK_SIZE, blankSave, pickedBerry, packFromBasket, spendCafeBerries, readSave, cafeBerries, emptyPackSlots, movePackBerry } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
assert.equal(PACK_SIZE, 12);
const state = { ...blankSave, raw: Array.from({ length: 16 }, (_, i) => pickedBerry(i)), sorted: { large: 2, regular: 3, processing: 1 }, boxes: 4, harvested: 16 };
const ids = state.raw.slice(0, PACK_SIZE).map((berry) => berry.id);
assert.equal(packFromBasket(state, ids.slice(0, 11)), null);
assert.equal(packFromBasket(state, [...ids.slice(0, 11), ids[0]]), null);
assert.equal(packFromBasket(state, [...ids.slice(0, 11), "missing"]), null);
const packed = packFromBasket(state, ids);
assert.equal(packed.boxes, 5);
assert.deepEqual(packed.raw, state.raw.slice(12));
assert.deepEqual(packed.packs[0], state.raw.slice(0, 12));
assert.deepEqual(packed.sorted, state.sorted);
assert.equal(state.raw.length, 16);
assert.equal(packFromBasket(packed, ids), null);
const onlyPacks = { ...state, raw: [], sorted: { ...state.sorted, processing: 0 } };
assert.equal(cafeBerries(onlyPacks), 16);
const opened = spendCafeBerries(onlyPacks, 1);
assert.equal(opened.boxes, 3);
assert.equal(opened.raw.length, 3);
assert.equal(cafeBerries(opened), 15);
assert.equal(spendCafeBerries({ ...onlyPacks, boxes: 0 }, 1), null);
assert.equal(spendCafeBerries(onlyPacks, 0), null);
assert.equal(spendCafeBerries(onlyPacks, -1), null);
const knownPack = packFromBasket({ ...state, boxes: 0, packs: [] }, ids);
const unpackKnown = spendCafeBerries({ ...knownPack, raw: [], sorted: { large: 0, regular: 0, processing: 0 } }, 2);
assert.equal(unpackKnown.boxes, 0);
assert.deepEqual(unpackKnown.raw, state.raw.slice(2, 12));
const legacyPack = { ...onlyPacks, boxes: 1, packs: [state.raw.slice(0, 4)] };
assert.equal(cafeBerries(readSave(legacyPack)), 4);
const mixed = { ...onlyPacks, boxes: 3, packs: [state.raw.slice(0, 4), state.raw.slice(0, 12)] };
assert.equal(cafeBerries(readSave(mixed)), 20);
const mixedOrder = spendCafeBerries(mixed, 15);
assert.equal(mixedOrder.boxes, 1);
assert.equal(cafeBerries(mixedOrder), 5);
let slots = movePackBerry(emptyPackSlots(), ids[0], 11);
assert.equal(slots.length, 12);assert.equal(slots[11], ids[0]);
slots = movePackBerry(slots, ids[1], 0);
slots = movePackBerry(slots, ids[0], 0);
assert.equal(slots[0], ids[0]);assert.equal(slots[11], ids[1]);
slots = movePackBerry(slots, ids[0], null);
assert.equal(slots[0], null);assert.equal(slots[11], ids[1]);
assert.deepEqual(movePackBerry(slots, ids[0], -1), slots);
assert.deepEqual(movePackBerry(slots, ids[0], 12), slots);
const largeBasket = Array.from({length: 2005}, (_, i) => ({...state.raw[0], id: 'large-'+i}));
assert.equal(readSave({...state, raw: largeBasket}).raw.length, 2005);
const ordered = spendCafeBerries(state, 2);
assert.equal(ordered.boxes, state.boxes);assert.equal(ordered.raw.length, 15);assert.equal(ordered.sorted.processing, 0);assert.equal(ordered.drinks, 1);
assert.equal(readSave({ berries: 3, watered: -2 }).raw.length, 3);
assert.equal(readSave({ berries: 3, watered: -2 }).watered, 0);
console.log("Inventory validation passed: twelve-berry packing, stock guards, exact contents, mixed legacy packs, cafe spending, drag slots and saved-state migration.");
