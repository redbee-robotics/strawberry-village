import fs from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";

const source = fs.readFileSync(new URL("../app/farm-state.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { blankSave, pickedBerry, packFromBasket, spendCafeBerries, readSave, cafeBerries, emptyPackSlots, movePackBerry } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const state = { ...blankSave, raw: Array.from({ length: 6 }, (_, i) => pickedBerry(i)), sorted: { large: 2, regular: 3, processing: 1 }, boxes: 4, harvested: 6 };
const ids = state.raw.slice(0, 4).map((berry) => berry.id);
assert.equal(packFromBasket(state, ids.slice(0, 3)), null);
assert.equal(packFromBasket(state, [ids[0], ids[0], ids[1], ids[2]]), null);
assert.equal(packFromBasket(state, [...ids.slice(0, 3), "missing"]), null);
const packed = packFromBasket(state, ids);
assert.equal(packed.boxes, 5);
assert.deepEqual(packed.raw, state.raw.slice(4));
assert.deepEqual(packed.sorted, state.sorted);
assert.equal(state.raw.length, 6);
assert.equal(packFromBasket(packed, ids), null);
const onlyPacks = { ...state, raw: [], sorted: { ...state.sorted, processing: 0 } };
assert.equal(cafeBerries(onlyPacks), 16);
const opened = spendCafeBerries(onlyPacks, 1);
assert.equal(opened.boxes, 3);
assert.equal(opened.raw.length, 3);
assert.equal(cafeBerries(opened), 15);
assert.equal(spendCafeBerries({ ...onlyPacks, boxes: 0 }, 1), null);
assert.equal(spendCafeBerries(onlyPacks, 0), null);
assert.equal(spendCafeBerries(onlyPacks, -1), null);
const knownPack = packFromBasket({ ...state, boxes: 0, packs: [] }, ids);
const unpackKnown = spendCafeBerries({ ...knownPack, raw: [], sorted: { large: 0, regular: 0, processing: 0 } }, 1);
assert.equal(unpackKnown.boxes, 0);
assert.deepEqual(unpackKnown.raw, state.raw.slice(1, 4));
let slots = movePackBerry(emptyPackSlots(), ids[0], 2);
assert.deepEqual(slots, [null, null, ids[0], null]);
slots = movePackBerry(slots, ids[1], 0);
slots = movePackBerry(slots, ids[0], 0);
assert.deepEqual(slots, [ids[0], null, ids[1], null]);
slots = movePackBerry(slots, ids[0], null);
assert.deepEqual(slots, [null, null, ids[1], null]);
assert.deepEqual(movePackBerry(slots, ids[0], -1), slots);
const largeBasket = Array.from({length: 2005}, (_, i) => ({...state.raw[0], id: 'large-'+i}));
assert.equal(readSave({...state, raw: largeBasket}).raw.length, 2005);
const ordered = spendCafeBerries(state, 2);
assert.equal(ordered.boxes, state.boxes);
assert.equal(ordered.raw.length, 5);
assert.equal(ordered.sorted.processing, 0);
assert.equal(ordered.sorted.large, state.sorted.large);
assert.equal(ordered.drinks, 1);
assert.equal(readSave({ berries: 3, watered: -2 }).raw.length, 3);
assert.equal(readSave({ berries: 3, watered: -2 }).watered, 0);
console.log("Inventory validation passed: incomplete/duplicate/missing selections, atomic packing, repeat protection, cafe spending, saved-state migration.");
